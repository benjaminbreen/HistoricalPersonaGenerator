/**
 * constants/gameData/disruptionWindows.ts
 *
 * When and where the ordinary run of life was interrupted.
 *
 * Every entry answers one question: if the generator draws a person here, in
 * this year, what is the chance their life was bent by something the steady-
 * state tables know nothing about — and if it was, what work did they end up
 * doing, what happened to them, and how did they die?
 *
 * On `severity`. It is the share of lives materially shaped, not a measure of
 * how bad the episode was in the abstract. The Black Death is 0.9 because
 * almost nobody in Europe in 1349 got through it untouched. The Crimean War is
 * 0.12 because for most people in the Russian Empire it was news. Two episodes
 * can be equally terrible and differ by a factor of eight here.
 *
 * On coverage. The aim is that no century in any zone is silent, not that every
 * war is listed. Wars that displaced few people and killed fewer are left out
 * on purpose; a table that fires on everything is the same as one that fires on
 * nothing. Where an episode is genuinely continental — the Black Death, the
 * virgin-soil epidemics, the two world wars — it has no `places` and covers the
 * zone.
 *
 * On `boost` and `damp`. Boost is the work the episode creates or forces people
 * into; damp is the settled career it interrupts. Both are matched against the
 * profession string, so they must use the vocabulary of `professions.ts` rather
 * than the vocabulary of historians.
 */

